CREATE TABLE IF NOT EXISTS app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS canteens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  name VARCHAR(80) NOT NULL,
  location VARCHAR(200) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(user_id, name)
);
CREATE TABLE IF NOT EXISTS stalls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  canteen_id BIGINT NOT NULL REFERENCES canteens(id),
  name VARCHAR(80) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(user_id, canteen_id, name)
);
CREATE TABLE IF NOT EXISTS dishes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  stall_id BIGINT NOT NULL REFERENCES stalls(id),
  name VARCHAR(80) NOT NULL,
  price DECIMAL(10,2) NOT NULL CHECK(price >= 0),
  category VARCHAR(30) NOT NULL,
  flavors VARCHAR(300) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(user_id, stall_id, name)
);
CREATE TABLE IF NOT EXISTS dish_marks (
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  dish_id BIGINT NOT NULL REFERENCES dishes(id),
  favorite BOOLEAN NOT NULL DEFAULT FALSE,
  avoided BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY(user_id, dish_id),
  CHECK(NOT(favorite AND avoided))
);
CREATE TABLE IF NOT EXISTS dish_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  dish_id BIGINT NOT NULL REFERENCES dishes(id),
  filename VARCHAR(100) NOT NULL UNIQUE,
  content_type VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS meals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  eaten_at TIMESTAMP NOT NULL,
  meal_type VARCHAR(20) NOT NULL,
  note VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS meal_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meal_id BIGINT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
  dish_id BIGINT NOT NULL REFERENCES dishes(id),
  dish_name VARCHAR(80) NOT NULL,
  quantity INTEGER NOT NULL CHECK(quantity > 0),
  paid_amount DECIMAL(10,2) NOT NULL CHECK(paid_amount >= 0),
  taste INTEGER CHECK(taste BETWEEN 1 AND 5),
  value_score INTEGER CHECK(value_score BETWEEN 1 AND 5),
  portion INTEGER CHECK(portion BETWEEN 1 AND 5),
  recommendation INTEGER CHECK(recommendation BETWEEN 1 AND 5),
  comment VARCHAR(1000) NOT NULL,
  CHECK((taste IS NULL AND value_score IS NULL AND portion IS NULL AND recommendation IS NULL)
     OR (taste IS NOT NULL AND value_score IS NOT NULL AND portion IS NOT NULL AND recommendation IS NOT NULL)),
  UNIQUE(meal_id, dish_id)
);
CREATE INDEX IF NOT EXISTS idx_meals_user_date ON meals(user_id,eaten_at);
CREATE INDEX IF NOT EXISTS idx_dishes_user_stall ON dishes(user_id,stall_id);
CREATE INDEX IF NOT EXISTS idx_meal_items_dish ON meal_items(dish_id);

CREATE TABLE IF NOT EXISTS experience_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meal_id BIGINT NOT NULL,
  dish_id BIGINT NOT NULL,
  content_type VARCHAR(30) NOT NULL,
  image_data BLOB NOT NULL,
  FOREIGN KEY(meal_id,dish_id) REFERENCES meal_items(meal_id,dish_id) ON DELETE CASCADE
);
